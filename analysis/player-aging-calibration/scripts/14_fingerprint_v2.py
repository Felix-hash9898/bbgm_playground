"""Formula fingerprint v2 for the user's long-running saves.

Fixes vs round 1: (a) the change is measured from the LAST ratings row of season s to the FIRST row of
season s+1 (= the preseason development only; mid-season permanent-injury rows are excluded);
(b) each player's predicted change uses his team's coaching effect (budget level -> levelToEffect, as
coachingEffect in budgetLevels.ts); (c) besides mean z-scores, full-distribution tests (two-sample KS
of observed vs simulated changes, per rating group and age band) and an explicit three-way verdict:
  "consistent with Playground"  : Playground not rejected (all Bonferroni-corrected KS p > 0.01 and |z| < 4)
  "closer to Playground only"   : Playground fits better but is itself rejected
  "consistent with Official" / "neither"
Being consistent with Playground does NOT prove the save was generated by it (an unknown variant could
also fit); it shows the data cannot distinguish it from Playground while rejecting Official.
Output: results/fingerprint_v2.csv, results/fingerprint_v2_summary.json
"""
from __future__ import annotations

import gzip
import json
import math

import numpy as np
import pandas as pd
from scipy import stats

from bbgm_dev import KEYS, develop_season
from common import RESULTS, SAVES, dump_json

SAVE_FILES = ["BBGM_League_7_2020_regular_season_4-0.json.gz", "BBGM_League_10_2028_draft.json.gz", "BBGM_League_6_2029_free_agency.json.gz",
              "BBGM_League_9_2022_re_sign_players.json.gz", "BBGM_League_3_2025_re_sign_players.json.gz"]


def coaching_effect(level):
    x = 3 * (round(level) - 1) / 99 - 1
    eff = 1.1 * x if x < 0 else 1.1 * math.tanh(x)
    return 0.09 * eff


GROUPS = {"stre": ["stre"], "athletic": ["spd", "jmp"], "shooting": ["ins", "fg", "tp", "ft"], "iq": ["oiq", "diq"], "endu": ["endu"]}
BANDS = [(19, 23), (24, 28), (29, 32), (33, 40)]
rng = np.random.default_rng(424242)
rows = []
for f in SAVE_FILES:
    d = json.load(gzip.open(SAVES / f))
    ga = d["gameAttributes"]
    ga = {x["key"]: x["value"] for x in ga} if isinstance(ga, list) else ga
    start = ga["startingSeason"]
    ce_by_tid = {t["tid"]: coaching_effect(t["budget"]["coaching"]) for t in d["teams"] if isinstance(t.get("budget"), dict)}
    recs = []
    for p in d["players"]:
        by = {}
        for r in p["ratings"]:
            by.setdefault(r["season"], []).append(r)
        tid_by_season = {}
        for s in p.get("stats", []):
            if not s.get("playoffs"):
                tid_by_season[s["season"]] = s["tid"]
        for s1, rows1 in by.items():
            s0 = s1 - 1
            if s1 <= start or s0 not in by:
                continue
            r0, r1 = by[s0][-1], rows1[0]
            if r1.get("locked") or r0.get("locked"):
                continue
            age = s1 - p["born"]["year"]
            if not 19 <= age <= 40:
                continue
            tid = tid_by_season.get(s0, p["tid"])
            recs.append({"season": s1, "age": age, "ce": ce_by_tid.get(tid, 0.0), **{f"p_{k}": r0[k] for k in ["hgt"] + KEYS},
                         **{k: r1[k] for k in KEYS}})
    df = pd.DataFrame(recs)
    for s1, grp in df.groupby("season"):
        if len(grp) < 80:
            continue
        REP = 40
        R0 = {k: np.repeat(grp[f"p_{k}"].to_numpy(float), REP) for k in ["hgt"] + KEYS}
        ages = np.repeat(grp["age"].to_numpy(), REP)
        ce = np.repeat(grp["ce"].to_numpy(), REP)
        res = {"save": f, "season": int(s1), "n": len(grp)}
        for form in ["official", "playground"]:
            R1 = develop_season(R0, ages, rng, form, coaching_effect=ce)
            pvals, zs = [], []
            for gname, keys in GROUPS.items():
                for lo, hi in BANDS:
                    m = (grp["age"] >= lo) & (grp["age"] <= hi)
                    if m.sum() < 25:
                        continue
                    mm = np.repeat(m.to_numpy(), REP)
                    obs = np.concatenate([(grp.loc[m, k] - grp.loc[m, f"p_{k}"]).to_numpy(float) for k in keys])
                    sim = np.concatenate([(R1[k] - R0[k])[mm] for k in keys])
                    pvals.append(stats.ks_2samp(obs, sim).pvalue)
                    zs.append((obs.mean() - sim.mean()) / (obs.std(ddof=1) / np.sqrt(len(obs)) + 1e-9))
            ntest = len(pvals)
            res[f"{form}_min_p_bonf"] = float(min(1.0, min(pvals) * ntest))
            res[f"{form}_max_abs_z"] = float(np.max(np.abs(zs)))
            res[f"{form}_n_tests"] = ntest
        fitp = res["playground_min_p_bonf"] > 0.01 and res["playground_max_abs_z"] < 4
        fito = res["official_min_p_bonf"] > 0.01 and res["official_max_abs_z"] < 4
        closer = res["playground_max_abs_z"] < res["official_max_abs_z"]
        res["verdict"] = ("consistent with Playground" if fitp and not fito else "consistent with Official" if fito and not fitp
                          else "consistent with both" if fitp and fito else "closer to Playground only" if closer else "closer to Official only")
        rows.append(res)
out = pd.DataFrame(rows)
out.to_csv(RESULTS / "fingerprint_v2.csv", index=False)
summ = {"offseasons": int(len(out)), "verdicts": out["verdict"].value_counts().to_dict(),
        "official_rejected_everywhere": bool((out["official_min_p_bonf"] < 0.01).all())}
dump_json(summ, RESULTS / "fingerprint_v2_summary.json")
pd.set_option("display.width", 250)
print(out.round(4).to_string())
print(summ)
